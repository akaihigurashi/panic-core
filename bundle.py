#!/usr/bin/env python3
"""
bundle.py - build a single-file scanner from panic-core and a scanner's check module.

    python3 bundle.py ../php2scan/check.py            # writes ../php2scan/php2scan.py and web.py
    python3 bundle.py ../php2scan/check.py --check    # only verify the generated files are current
    python3 bundle.py --update-db                     # refresh vendor/webappanalyzer from GitHub
    python3 bundle.py ../newscan/check.py --scaffold --port 8091 --title "..."
                                                      # + Dockerfile, compose, workflows, nginx example

The result is one Python file with no dependencies: the engine (fetching,
fingerprinting, port scan, vhost discovery, CLI), the check module (its
fingerprints, verdicts, optional probe) and the part of the webappanalyzer
fingerprint database the check needs (every technology that is one of the
check's TARGETS or implies one of them).

web.py (the public web page server) is copied next to it with the scanner's
module name filled in.
"""
import argparse
import ast
import glob
import json
import os
import subprocess
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
CORE = os.path.join(HERE, "core")
DB_DIR = os.path.join(HERE, "vendor", "webappanalyzer", "technologies")
DB_COMMIT = os.path.join(HERE, "vendor", "webappanalyzer", "COMMIT")
DB_REPO = "enthec/webappanalyzer"
KEEP_FIELDS = ("headers", "cookies", "meta", "html", "scriptSrc", "url", "implies")


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def load_db():
    techs = {}
    for f in sorted(glob.glob(os.path.join(DB_DIR, "*.json"))):
        techs.update(json.loads(read(f)))
    commit, date = read(DB_COMMIT).split()
    return techs, commit, date


def closure(techs, targets):
    def implies(t):
        v = techs.get(t, {}).get("implies", [])
        return [x.split("\\;")[0] for x in ([v] if isinstance(v, str) else v)]
    found = set(targets)
    changed = True
    while changed:
        changed = False
        for t in techs:
            if t not in found and any(i in found for i in implies(t)):
                found.add(t)
                changed = True
    return found


def embedded_db(targets):
    techs, commit, date = load_db()
    wanted = sorted(closure(techs, targets) & set(techs), key=str.lower)
    lines = []
    for t in wanted:
        d = {k: techs[t][k] for k in KEEP_FIELDS if k in techs[t]}
        lines.append(json.dumps(t) + ":" + json.dumps(d, ensure_ascii=False, separators=(",", ":"),
                                                      sort_keys=True))
    body = "{\n" + ",\n".join(lines) + "\n}"
    assert "'''" not in body
    head = (f"# --- embedded fingerprint database ------------------------------------------\n"
            f"# {len(wanted)} technologies ({', '.join(sorted(targets))} and everything running on them)\n"
            f"# extracted from webappanalyzer (open Wappalyzer fork), https://github.com/{DB_REPO},\n"
            f"# commit {commit[:7]} ({date}), GPL-3.0. Fields kept: {', '.join(KEEP_FIELDS)}.\n"
            f"# Refresh with -U (a downloaded copy takes precedence).\n")
    return head + f'EMBEDDED_RULES_DATE = "{date}"\nEMBEDDED_RULES = r\'\'\'' + body + "'''\n", len(wanted)


def core_rev():
    try:
        # rev-parse only reads: it never touches the index, so no .git/index.lock is left
        # behind (describe --dirty refreshes the index and can leave one on a read-only mount)
        return subprocess.run(["git", "-C", HERE, "rev-parse", "--short", "HEAD"],
                              capture_output=True, text=True, check=True).stdout.strip()
    except Exception:  # noqa: BLE001
        return "unknown"


def build(check_path):
    src = read(check_path)
    tree = ast.parse(src)
    doc = ast.get_docstring(tree, clean=False) or ""
    meta = {}
    for node in tree.body:                      # NAME, TARGETS ... without executing the module
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if node.targets[0].id in ("NAME", "VERSION", "TARGETS"):
                meta[node.targets[0].id] = ast.literal_eval(node.value)
    name = meta["NAME"]
    # strip the docstring and development-only lines from the check module
    body = src
    if doc:
        first = tree.body[0]
        lines = src.splitlines(keepends=True)
        body = "".join(lines[first.end_lineno:])
    body = "".join(l for l in body.splitlines(keepends=True) if "# bundle: strip" not in l).strip("\n")
    engine = read(os.path.join(CORE, "engine.py")).strip("\n")
    db, n_db = embedded_db(meta["TARGETS"])
    out = (
        "#!/usr/bin/env python3\n"
        f'"""{doc}"""\n'
        f"# {name} {meta['VERSION']} - single file, Python 3 standard library only.\n"
        f"# GENERATED by panic-core/bundle.py (core {core_rev()}) from check.py - edit check.py\n"
        f"# in the {name} repository or the engine in panic-core, then rebuild.\n"
        "# License: GPL-3.0 (includes webappanalyzer fingerprint data, GPL-3.0).\n"
        "\n" + engine + "\n\n\n"
        "# ===========================================================================\n"
        f"# {name} check: fingerprints, verdicts and everything specific to this scanner\n"
        "# ===========================================================================\n"
        + body + "\n\n\n" + db + "\n\ninit()\n\nif __name__ == \"__main__\":\n    main()\n"
    )
    web = read(os.path.join(CORE, "web.py")).replace("@SCANNER@", name)
    return name, out, web, n_db


def scaffold(dest, name, title, port):
    """Copy templates/scanner into a scanner repository (existing files are kept)."""
    root = os.path.join(HERE, "templates", "scanner")
    n = (port - 8000) % 250
    subst = {"@NAME@": name, "@TITLE@": title, "@PORT@": str(port),
             "@SUBNET@": f"172.30.{n}.0/24", "@GATEWAY@": f"172.30.{n}.1"}
    for dirpath, _, files in os.walk(root):
        for f in files:
            src = os.path.join(dirpath, f)
            dst = os.path.join(dest, os.path.relpath(src, root))
            if os.path.exists(dst):
                print(f"kept existing {dst}")
                continue
            text = read(src)
            for k, v in subst.items():
                text = text.replace(k, v)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            with open(dst, "w", encoding="utf-8") as fh:
                fh.write(text)
            print(f"created {dst}")


def update_db():
    api = f"https://api.github.com/repos/{DB_REPO}/commits/main"
    with urllib.request.urlopen(api, timeout=30) as r:
        c = json.load(r)
    sha, date = c["sha"], c["commit"]["committer"]["date"][:10]
    raw = f"https://raw.githubusercontent.com/{DB_REPO}/{sha}/src/technologies/{{}}.json"
    for n in ["_"] + [chr(x) for x in range(ord("a"), ord("z") + 1)]:
        with urllib.request.urlopen(raw.format(n), timeout=30) as r:
            data = r.read()
        json.loads(data)
        with open(os.path.join(DB_DIR, f"{n}.json"), "wb") as f:
            f.write(data)
    with open(DB_COMMIT, "w") as f:
        f.write(f"{sha} {date}\n")
    print(f"webappanalyzer updated to {sha[:7]} ({date})")


def main():
    ap = argparse.ArgumentParser(description="Build a single-file panic-core scanner.")
    ap.add_argument("check", nargs="?", help="path to the scanner's check.py")
    ap.add_argument("-o", "--out", help="output directory (default: next to check.py)")
    ap.add_argument("--check", dest="verify", action="store_true",
                    help="don't write, exit 1 if the generated files are out of date")
    ap.add_argument("--update-db", action="store_true", help="refresh the vendored fingerprint database")
    ap.add_argument("--scaffold", action="store_true",
                    help="also create Dockerfile, compose file, workflows and nginx example (from templates/)")
    ap.add_argument("--port", type=int, default=8088, help="container port for --scaffold")
    ap.add_argument("--title", default="", help="one-line description for --scaffold")
    a = ap.parse_args()
    if a.update_db:
        update_db()
    if not a.check:
        if not a.update_db:
            ap.error("no check.py given")
        return
    name, out, web, n_db = build(a.check)
    dest = a.out or os.path.dirname(os.path.abspath(a.check))
    files = {os.path.join(dest, f"{name}.py"): out, os.path.join(dest, "web.py"): web}
    if a.verify:
        stale = [p for p, c in files.items() if not os.path.exists(p) or read(p) != c]
        # the core revision line differs between checkouts: compare without it
        stale = [p for p in stale if not os.path.exists(p) or
                 [l for l in read(p).splitlines() if "GENERATED by panic-core" not in l]
                 != [l for l in files[p].splitlines() if "GENERATED by panic-core" not in l]]
        for p in stale:
            print(f"out of date: {p}", file=sys.stderr)
        sys.exit(1 if stale else 0)
    for p, c in files.items():
        with open(p, "w", encoding="utf-8") as f:
            f.write(c)
    os.chmod(os.path.join(dest, f"{name}.py"), 0o755)
    if a.scaffold:
        scaffold(dest, name, a.title or name, a.port)
    print(f"built {name}.py ({len(out) // 1024} KB, {n_db} database technologies) and web.py in {dest}")


if __name__ == "__main__":
    main()
